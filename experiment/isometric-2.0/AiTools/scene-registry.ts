/**
 * scene-registry.ts — Pre-defined test scenes for the AiTools renderer.
 *
 * Now imports directly from game source (solver.ts) so all nano SVGs use the
 * actual game engine generators — the same code path the browser uses.
 * Base tile (biome) SVGs are still generated locally since those are pure canvas.
 *
 * Usage:
 *   const chain = resolveScene('wall-h-run');
 *   renderSvg('<svg/>', { mode: 'isometric_assembly', assemblyChain: chain, ... });
 *
 * Built-in named scenes:
 *   wall-h-run       — 8-tile horizontal stone-wall run
 *   wall-v-run       — 8-tile vertical stone-wall run
 *   fence-perimeter  — 4×4 fence box with gate
 *   river-crossing   — river segment with bridge
 *   tall-grass-patch — scattered tall-grass on grass terrain
 *   homestead        — homestead-wall assembly (3×3 footprint)
 *   mixed-biomes     — showcase of all terrain tile kinds
 *   all-nanos        — showcase of every NanoTileKind
 *
 * TODO: DOC
 */

import type { AssemblyChainItem } from './svg-renderer-tool.js';
// Import game engine SVG generators directly — no more duplicated color maps
import { getVariantSvg, woodenFenceSvg } from '../src/solver.js';
import type { FeatureVariant, FeatureConnections } from '../src/types.js';

// ─── Types ───────────────────────────────────────────────────

export type TileKind = 'grass' | 'dirt' | 'rock' | 'water' | 'sand' | 'dry-grass';
export type NanoKind =
  | 'fence' | 'stone-wall' | 'river' | 'river-bank' | 'bridge'
  | 'tall-grass' | 'gate' | 'troll-bridge' | 'cathedral-wall' | 'homestead-wall';

/** One entry in a scene descriptor. */
export interface SceneEntry {
  /** TileKind or NanoKind slug. */
  kind: TileKind | NanoKind;
  col: number;
  row: number;
  /** Feature variant for nano tiles. Inferred from position in run if omitted. */
  variant?: FeatureVariant;
  /** Optional display label for annotation. */
  label?: string;
}

/** A named set of tile entries that compose a test scene. */
export interface SceneDescriptor {
  name: string;
  description: string;
  entries: SceneEntry[];
  /** Recommended canvas width for this scene. */
  canvasWidth?: number;
  canvasHeight?: number;
}

// ─── Base tile colors (mirrors KIND_COLORS in chunk.ts) ──────

const TILE_COLORS: Record<TileKind, string> = {
  'grass':    '#4a7c4e',
  'dirt':     '#8b6f47',
  'rock':     '#6b6b6b',
  'water':    '#1e6b8c',
  'sand':     '#c2a05a',
  'dry-grass':'#8b7a32',
};

/**
 * Generate a base-tile SVG (128×128) for a TileKind.
 * Used for ground reference tiles in scenes.
 */
function makeTileSvg(kind: TileKind, col: number, row: number): string {
  const base = TILE_COLORS[kind];
  const rVariance = ((col * 7 + row * 13) & 0x0f) - 8;
  const gVariance = ((col * 11 + row * 3) & 0x0f) - 8;
  const rr = Math.max(0, Math.min(255, parseInt(base.slice(1, 3), 16) + rVariance));
  const gg = Math.max(0, Math.min(255, parseInt(base.slice(3, 5), 16) + gVariance));
  const bb = parseInt(base.slice(5, 7), 16);
  let detail = '';
  if (kind === 'grass') detail = `<line x1="0" y1="64" x2="128" y2="64" stroke="rgba(0,0,0,0.08)" stroke-width="1"/>`;
  else if (kind === 'water') detail = `<rect x="0" y="48" width="128" height="32" fill="rgba(255,255,255,0.07)" rx="2"/>`;
  else if (kind === 'rock') detail = `<polygon points="20,40 50,20 80,40 60,70 30,70" fill="rgba(0,0,0,0.15)"/>`;
  else if (kind === 'sand') detail = `<circle cx="32" cy="40" r="4" fill="rgba(255,255,255,0.12)"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128"><rect width="128" height="128" fill="rgb(${rr},${gg},${bb})"/>${detail}<text x="64" y="64" text-anchor="middle" dy=".35em" font-size="8" fill="rgba(255,255,255,0.35)">${kind}</text></svg>`;
}

// ─── Nano kind metadata (zMode/zOffset/walkable — NOT SVG colors) ────────────
// SVG content is now generated by solver.ts directly via getVariantSvg().

const NANO_KINDS = new Set<NanoKind>([
  'fence', 'stone-wall', 'river', 'river-bank', 'bridge',
  'tall-grass', 'gate', 'troll-bridge', 'cathedral-wall', 'homestead-wall',
]);

const NANO_Z: Record<NanoKind, number> = {
  'fence':          2,
  'stone-wall':     4,
  'river':         -2,
  'river-bank':     1,
  'bridge':         0,
  'tall-grass':     0,
  'gate':           2,
  'troll-bridge':   1,
  'cathedral-wall': 6,
  'homestead-wall': 3,
};

const NANO_Z_MODE: Record<NanoKind, 'positive' | 'negative' | 'flat'> = {
  'fence':          'positive',
  'stone-wall':     'positive',
  'river':          'negative',
  'river-bank':     'flat',
  'bridge':         'flat',
  'tall-grass':     'flat',
  'gate':           'positive',
  'troll-bridge':   'positive',
  'cathedral-wall': 'positive',
  'homestead-wall': 'positive',
};

const NANO_WALKABLE: Record<NanoKind, boolean> = {
  'fence':          false,
  'stone-wall':     false,
  'river':          false,
  'river-bank':     true,
  'bridge':         true,
  'tall-grass':     true,
  'gate':           true,
  'troll-bridge':   true,
  'cathedral-wall': false,
  'homestead-wall': false,
};

// ─── SVG Generators ──────────────────────────────────────────

function isNanoKind(kind: string): kind is NanoKind {
  return NANO_KINDS.has(kind as NanoKind);
}

/**
 * Get the nano SVG from the actual game engine via solver.ts.
 * This is the CANONICAL source — same code path as the browser game.
 * Falls back to woodenFenceSvg for fence kinds if getVariantSvg returns null.
 */
function makeNanoSvg(kind: NanoKind, variant: FeatureVariant | undefined, col: number, row: number): string {
  // Default connections from variant (straight run = connected both ends)
  const connections = inferConnectionsForVariant(variant ?? 'straight-h');
  const zOffset = NANO_Z[kind];

  // getVariantSvg returns null for unknown kinds — fall back to woodenFenceSvg for fence group
  const svg = getVariantSvg(kind as Parameters<typeof getVariantSvg>[0], variant ?? 'straight-h', connections, Math.abs(zOffset), col, row);
  if (svg) return svg;

  // Last resort: woodenFenceSvg for fence/gate family
  if (kind === 'fence' || kind === 'gate' || kind === 'troll-bridge' || kind === 'bridge') {
    return woodenFenceSvg(variant ?? 'straight-h');
  }

  // Style-neutral fallback: labeled grey rect (should never reach here)
  return `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128"><rect width="128" height="128" fill="#555"/><text x="64" y="64" text-anchor="middle" dy=".35em" font-size="10" fill="#fff">${kind}</text></svg>`;
}

/**
 * Infer FeatureConnections from a variant for scene assembly.
 * Straight runs have both ends connected; end tiles have one; isolated has none.
 */
function inferConnectionsForVariant(variant: FeatureVariant): FeatureConnections {
  switch (variant) {
    case 'straight-h': return { top: false, right: true,  bottom: false, left: true };
    case 'straight-v': return { top: true,  right: false, bottom: true,  left: false };
    case 'cross':      return { top: true,  right: true,  bottom: true,  left: true };
    case 'end-r':      return { top: false, right: true,  bottom: false, left: false };
    case 'end-l':      return { top: false, right: false, bottom: false, left: true };
    case 'end-t':      return { top: true,  right: false, bottom: false, left: false };
    case 'end-b':      return { top: false, right: false, bottom: true,  left: false };
    case 'corner-tr':  return { top: true,  right: true,  bottom: false, left: false };
    case 'corner-tl':  return { top: true,  right: false, bottom: false, left: true };
    case 'corner-br':  return { top: false, right: true,  bottom: true,  left: false };
    case 'corner-bl':  return { top: false, right: false, bottom: true,  left: true };
    case 'tee-t':      return { top: true,  right: true,  bottom: false, left: true };
    case 'tee-r':      return { top: true,  right: true,  bottom: true,  left: false };
    case 'tee-b':      return { top: false, right: true,  bottom: true,  left: true };
    case 'tee-l':      return { top: true,  right: false, bottom: true,  left: true };
    case 'isolated':   return { top: false, right: false, bottom: false, left: false };
    default:           return { top: true,  right: true,  bottom: true,  left: true };
  }
}

// ─── Scene Resolution ─────────────────────────────────────────

/**
 * Resolve a SceneDescriptor into an AssemblyChainItem[] ready for renderSvg.
 * Nano tile SVGs come from the actual game engine (solver.ts).
 */
export function resolveScene(descriptor: SceneDescriptor): AssemblyChainItem[] {
  return descriptor.entries.map((entry) => {
    const { kind, col, row, variant } = entry;
    if (isNanoKind(kind)) {
      return {
        svg: makeNanoSvg(kind, variant, col, row),
        col,
        row,
        zMode: NANO_Z_MODE[kind],
        zOffset: NANO_Z[kind],
        walkable: NANO_WALKABLE[kind],
      };
    } else {
      return {
        svg: makeTileSvg(kind as TileKind, col, row),
        col,
        row,
        zMode: 'flat' as const,
        zOffset: 0,
        walkable: true,
      };
    }
  });
}

/**
 * Resolve a named scene by ID to an AssemblyChainItem array.
 * Throws if the scene name is not found.
 */
export function resolveNamedScene(name: string): { chain: AssemblyChainItem[]; descriptor: SceneDescriptor } {
  const descriptor = BUILT_IN_SCENES[name];
  if (!descriptor) {
    const available = Object.keys(BUILT_IN_SCENES).join(', ');
    throw new Error(`Unknown scene "${name}". Available: ${available}`);
  }
  return { chain: resolveScene(descriptor), descriptor };
}

/** Returns all built-in scene names and descriptions. */
export function listScenes(): { name: string; description: string; tileCount: number; canvasWidth?: number; canvasHeight?: number }[] {
  return Object.values(BUILT_IN_SCENES).map(s => ({
    name: s.name,
    description: s.description,
    tileCount: s.entries.length,
    canvasWidth: s.canvasWidth,
    canvasHeight: s.canvasHeight,
  }));
}

// ─── Built-in Scenes ─────────────────────────────────────────

function grassRow(cols: number[], row: number): SceneEntry[] {
  return cols.map(col => ({ kind: 'grass' as TileKind, col, row }));
}

function nanoRow(kind: NanoKind, cols: number[], row: number): SceneEntry[] {
  return cols.map(col => ({ kind, col, row, label: `${kind}(${col},${row})` }));
}

