/** Nano kinds that use 3-face extruded box rendering via buildExtrudedFaceMarkup(). */
const EXTRUDED_NANO_KINDS = new Set<NanoKind>(['stone-wall', 'cathedral-wall', 'homestead-wall']);
const CONNECTABLE_NANO_KINDS = new Set<NanoKind>(['stone-wall', 'cathedral-wall', 'homestead-wall', 'fence', 'river']);

// ─── Types ───────────────────────────────────────────────────

export type TileKind = 'grass' | 'dirt' | 'rock' | 'water' | 'sand' | 'dry-grass';
export type NanoKind =
  | 'fence' | 'stone-wall' | 'river' | 'river-bank' | 'bridge'
  | 'tall-grass' | 'gate' | 'troll-bridge' | 'cathedral-wall' | 'homestead-wall';

/** One entry in a scene descriptor. */
export interface SceneEntry {
  /** TileKind or NanoKind slug. */
  kind: TileKind | NanoKind;
  col: number;
  row: number;
  /** Feature variant for nano tiles. Inferred from position in run if omitted. */
  variant?: FeatureVariant;
  /** Optional per-entry nano height override for assembly proofs. */
  zOffset?: number;
  /** Optional procedural fence style id from src/textures/fence-family.ts. */
  fenceStyle?: string;
  /** Optional display label for annotation. */
  label?: string;
}

/** A named set of tile entries that compose a test scene. */
export interface SceneDescriptor {
  name: string;
  description: string;
  entries: SceneEntry[];
  /** Recommended canvas width for this scene. */
  canvasWidth?: number;
  canvasHeight?: number;
}

