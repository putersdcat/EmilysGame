// ─── Helpers ─────────────────────────────────────────────────

function groupBy<T>(items: T[], key: (item: T) => string): Record<string, T[]> {
  const groups: Record<string, T[]> = {};
  for (const item of items) {
    const k = key(item);
    if (!groups[k]) groups[k] = [];
    groups[k].push(item);
  }
  return groups;
}

function getSeverityIcon(severity: QASeverity): string {
  switch (severity) {
    case 'error': return '🔴';
    case 'warning': return '🟡';
    case 'info': return '🔵';
  }
}

function getCategoryIcon(category: QACheckCategory): string {
  switch (category) {
    case 'safety': return '🛡️';
    case 'readability': return '📖';
    case 'answer-consistency': return '✅';
    case 'length': return '📏';
    case 'age-appropriateness': return '👶';
    case 'completeness': return '📝';
    case 'duplicates': return '🔄';
  }
}
