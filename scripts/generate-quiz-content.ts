// ─── Conversion & Shard Generation ──────────────────────────

function convertToPackFormat(raw: RawQuizQuestion, index: number): QuizQuestionPack {
  const ageMetadata = createAgeMetadata(
    raw.ageBand === '5-7' ? 5 : raw.ageBand === '8-10' ? 8 : 11,
    raw.ageBand === '5-7' ? 7 : raw.ageBand === '8-10' ? 10 : null
  );

  const provenance = createProvenanceMetadata(
    raw.source,
    'CC0-1.0', // Public domain equivalent
    raw.sourceUrl,
    'content-pipeline-v1'
  );

  // Ensure correct answer is at index 0
  const reorderedAnswers = [...raw.answers];
  if (raw.correctIndex !== 0) {
    [reorderedAnswers[0], reorderedAnswers[raw.correctIndex]] =
      [reorderedAnswers[raw.correctIndex], reorderedAnswers[0]];
  }

  return {
    id: `q_${raw.category}_${raw.difficulty}_${String(index).padStart(3, '0')}`,
    category: raw.category,
    difficulty: raw.difficulty,
    ageMetadata,
    question: raw.question,
    answers: reorderedAnswers,
    hint: raw.hint,
    explanation: raw.explanation,
    rephraseHint: undefined,
    tags: raw.tags,
    provenance,
  };
}

function createShards(questions: QuizQuestionPack[]): QuizShard[] {
  const shards: QuizShard[] = [];

  for (let i = 0; i < questions.length; i += MAX_QUESTIONS_PER_SHARD) {
    const chunk = questions.slice(i, i + MAX_QUESTIONS_PER_SHARD);
    const shardNumber = Math.floor(i / MAX_QUESTIONS_PER_SHARD) + 1;

    shards.push({
      shardId: `quizzes-${String(shardNumber).padStart(3, '0')}`,
      schemaVersion: SCHEMA_VERSION,
      createdAt: new Date().toISOString(),
      questions: chunk,
    });
  }

  return shards;
}

// ─── Main Execution ──────────────────────────────────────────

function main() {
  console.log('🚀 Starting quiz content generation...');
  console.log(`📊 Processing ${CURATED_QUESTIONS.length} curated questions`);

  // Convert to pack format
  const packQuestions = CURATED_QUESTIONS.map((q, i) => convertToPackFormat(q, i));

  // Create shards
  const shards = createShards(packQuestions);

  // Ensure output directory exists
  const outputDir = path.join(__dirname, '../content/packs/default-v1/quizzes');
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Write shard files
  shards.forEach(shard => {
    const filename = `${shard.shardId}.json`;
    const filepath = path.join(outputDir, filename);
    fs.writeFileSync(filepath, JSON.stringify(shard, null, 2), 'utf-8');
    console.log(`✅ Written ${shard.questions.length} questions to ${filename}`);
  });

  // Generate statistics
  const stats = {
    totalQuestions: packQuestions.length,
    byCategory: {} as Record<string, number>,
    byDifficulty: {} as Record<string, number>,
    byAgeBand: {} as Record<string, number>,
  };

  packQuestions.forEach(q => {
    stats.byCategory[q.category] = (stats.byCategory[q.category] || 0) + 1;
    stats.byDifficulty[q.difficulty] = (stats.byDifficulty[q.difficulty] || 0) + 1;
    stats.byAgeBand[q.ageMetadata.ageBand] = (stats.byAgeBand[q.ageMetadata.ageBand] || 0) + 1;
  });

  console.log('\n📈 Generation Statistics:');
  console.log(`   Total: ${stats.totalQuestions} questions`);
  console.log(`   Categories: ${JSON.stringify(stats.byCategory, null, 2)}`);
  console.log(`   Difficulty: ${JSON.stringify(stats.byDifficulty, null, 2)}`);
  console.log(`   Age Bands: ${JSON.stringify(stats.byAgeBand, null, 2)}`);
  console.log(`\n✨ Content generation complete!`);
}

main();
